//Increment ++
//Decrement --

//post increment
let x:number=10;
let res1:number=x++;
console.log(res1); //10
console.log(x); //11

console.log("*******************");

//pre increment
let res2:number=++x;
console.log(res2); //12
console.log(x); //12

console.log("*******************");

//post decrement
let res3:number=x--;
console.log(res3); //12
console.log(x); //11

console.log("*******************");

//pre decrement
let res4:number=--x;
console.log(res4); //10
console.log(x); //10

